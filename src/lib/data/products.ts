import type { Availability, CategorySlug, Gender, Merchant, Offer, Product } from "@/lib/types";

type Tone = "navy" | "ice" | "lavender" | "sand" | "charcoal" | "rust";

const DEMO_TIMESTAMPS = [
  "2026-10-18T08:30:00+05:30",
  "2026-10-18T06:15:00+05:30",
  "2026-10-17T21:40:00+05:30",
];

function offer(merchant: Merchant, price: number, availability: Availability = "in_stock", t = 0): Offer {
  return { merchant, price, affiliateUrl: "#", availability, lastUpdated: DEMO_TIMESTAMPS[t % 3] };
}

interface Seed {
  id: string;
  name: string;
  brand: string;
  category: CategorySlug;
  gender: Gender;
  tone: Tone;
  rating: number;
  reviewCount: number;
  mrp: number;
  winterScore: number;
  description: string;
  highlights: string[];
  offers: Offer[];
}

/** Derives price (lowest purchasable offer) and discount so they never drift from offers. */
function build(seed: Seed): Product {
  const purchasable = seed.offers.filter((o) => o.availability !== "out_of_stock");
  const pool = purchasable.length ? purchasable : seed.offers;
  const price = Math.min(...pool.map((o) => o.price));
  const { tone, ...rest } = seed;
  return {
    ...rest,
    image: `/images/placeholders/${seed.category}-${tone}.svg`,
    price,
    discount: Math.max(0, Math.round((1 - price / seed.mrp) * 100)),
    isDemo: true,
  };
}

